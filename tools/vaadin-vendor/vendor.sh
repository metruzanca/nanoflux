#!/usr/bin/env bash
# Vendors the pinned Vaadin web components into
# internal/web/static/vaadin.bundle.js. Run with `mise run vendor:vaadin`.
#
# Vaadin publishes a tree of @vaadin/* ES modules that import each other by
# bare specifier, so a browser cannot load them directly. This installs the
# pinned versions in a throwaway dir and bundles the transitive closure into
# one minified ESM file with no runtime npm dependency. The output is committed
# (like htmx.min.js), so builds and self-hosting never touch npm.
set -euo pipefail

VAADIN_VERSION="25.3.0"
ESBUILD_VERSION="0.25.0"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/internal/web/static/vaadin.bundle.js"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "vendoring @vaadin/combo-box + @vaadin/multi-select-combo-box @ $VAADIN_VERSION"
cd "$WORK"
npm init -y >/dev/null 2>&1
npm install --no-audit --no-fund --silent \
  "@vaadin/combo-box@$VAADIN_VERSION" \
  "@vaadin/multi-select-combo-box@$VAADIN_VERSION" \
  "esbuild@$ESBUILD_VERSION"

cp "$ROOT/tools/vaadin-vendor/entry.js" entry.js
npx esbuild entry.js \
  --bundle --minify --format=esm \
  --banner:js="/* Vendored Vaadin web components v$VAADIN_VERSION — generated by mise run vendor:vaadin. Do not edit. */" \
  --outfile="$OUT" \
  --log-level=warning

echo "wrote $OUT ($(stat -c%s "$OUT") bytes)"
